// Regenerates src/claude-builtins.ts from the recorded `initialize` command list.
// Run: node packages/shared/scripts/claude-builtins.mjs
import { readFileSync, writeFileSync } from "node:fs";

const fixture = "packages/harness/fixtures/u3/control-initialize-commands.jsonl";
const root = new URL("../../../", import.meta.url);
const line = readFileSync(new URL(fixture, root), "utf8")
  .split("\n")
  .filter(Boolean)
  .map((l) => JSON.parse(l))
  .find((l) => l.type === "control_response");
const builtins = line.response.response.commands
  .filter((c) => c.builtin)
  .map((c) => ({
    name: c.name,
    description: c.description,
    argumentHint: c.argumentHint,
    aliases: c.aliases ?? [],
  }));

const out = `// Generated by packages/shared/scripts/claude-builtins.mjs. Do not edit.
// Source: ${fixture} (Claude Code 2.1.327).
// Regenerate: node packages/shared/scripts/claude-builtins.mjs
export type ClaudeBuiltin = {
  name: string;
  description: string;
  argumentHint: string;
  aliases: string[];
};

/** Claude Code's built-in commands, listed before an agent's first start, when no session list exists yet. */
export const CLAUDE_BUILTINS: readonly ClaudeBuiltin[] = ${JSON.stringify(builtins, null, 2)};
`;
writeFileSync(new URL("packages/shared/src/claude-builtins.ts", root), out);
console.log(`${builtins.length} built-ins`);
