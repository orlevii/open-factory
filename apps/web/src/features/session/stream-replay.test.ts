import {
  type LiveFrame,
  liveKey,
  type ServerMessage,
  type SessionEvent,
} from "@open-factory/shared";
import { describe, expect, test } from "vitest";
import interrupt from "@/test/fixtures/stream/partial-interrupt-mid-text.frames.json";
import subagent from "@/test/fixtures/stream/partial-subagent.frames.json";
import textAndWrite from "@/test/fixtures/stream/partial-text-and-write.frames.json";
import lateDelta from "@/test/fixtures/stream/partial-text-and-write-late-delta.frames.json";
import { detail } from "@/test/session-fixtures";
import { buildRows, textRowKey } from "./rows";
import {
  eventsInOrder,
  initialSessionState,
  type SessionState,
  sessionReducer,
} from "./session-state";

/**
 * U3 §11.4 fixture test, client half (Q35 condition 3): the frames the server published for the spike's recorded
 * streams (generated by `apps/server/src/agents/stream-replay.test.ts`) folded through `sessionReducer` one by one
 * show exactly one block per text block, and a reload at any point (the persisted events so far, then the server's
 * subscribe snapshot at that point) shows the same text.
 */

interface StreamFixture {
  trace: string;
  frames: ServerMessage[];
  snapshots: { after: number; reset: LiveFrame }[];
}

const FIXTURES: Record<string, unknown> = {
  "partial-text-and-write": textAndWrite,
  "partial-text-and-write-late-delta": lateDelta,
  "partial-interrupt-mid-text": interrupt,
  "partial-subagent": subagent,
};
const read = (name: string) => FIXTURES[name] as StreamFixture;

const events = (frames: readonly ServerMessage[]) =>
  frames.flatMap((f) => (f.type === "session_event" ? [f.event] : []));

function loaded(page: SessionEvent[]): SessionState {
  return sessionReducer(initialSessionState, {
    type: "loaded",
    page: { events: page, hasMore: { before: false, after: false } },
    detail: detail(
      {},
      [],
      page.reduce((m, e) => Math.max(m, e.seq), 0),
    ),
    mode: "latest",
  });
}

interface Block {
  key: string;
  text: string;
}

/** The text blocks the timeline renders: the top-level persisted text rows, then the live blocks. */
function rendered(s: SessionState): Block[] {
  const rows = buildRows(eventsInOrder(s)).rows.flatMap((r) =>
    r.kind === "text" ? [{ key: r.key, text: r.text }] : [],
  );
  const live = s.live.texts.map((t) => ({ key: textRowKey(t.messageId, t.index), text: t.text }));
  return [...rows, ...live];
}

/** Top-level block keys the frames have shown so far, minus those the server dropped with no row (`retire`). */
function keysSeen(frames: readonly ServerMessage[]): Set<string> {
  const keys = new Set<string>();
  for (const f of frames) {
    if (f.type === "session_event") {
      const e = f.event.event;
      if (e.type !== "assistant_text" || e.parentToolUseId) continue;
      keys.add(
        e.messageId !== undefined && e.blockIndex !== undefined
          ? textRowKey(e.messageId, e.blockIndex)
          : `${f.event.seq}`,
      );
    } else if (f.type === "live") {
      for (const t of f.texts ?? []) keys.add(textRowKey(t.messageId, t.index));
      // a live key is `messageId:index`, its row key `t:messageId:index`
      for (const k of f.retire ?? []) keys.delete(`t:${k}`);
    }
  }
  return keys;
}

function replay(name: string) {
  const fx = read(name);
  const snapshotAt = new Map(fx.snapshots.map((x) => [x.after, x.reset]));
  let s = loaded([]);
  let reloads = 0;
  fx.frames.forEach((frame, i) => {
    s = sessionReducer(s, { type: "frame", message: frame });
    const so = fx.frames.slice(0, i + 1);
    const blocks = rendered(s);
    const keys = blocks.map((b) => b.key);
    // never two blocks for one key, and one block for every key seen so far
    expect(new Set(keys).size, `frame ${i}`).toBe(keys.length);
    expect(keys.length, `frame ${i}`).toBe(keysSeen(so).size);
    // the frames carry every chunk in order: no offset gap, no snapshot asked for
    expect(s.snapshotWanted, `frame ${i}`).toBe(0);
    const reset = snapshotAt.get(i + 1);
    if (!reset) return;
    reloads += 1;
    const reloaded = sessionReducer(loaded(events(so)), { type: "frame", message: reset });
    expect(rendered(reloaded), `reload after frame ${i}`).toEqual(blocks);
  });
  expect(reloads).toBe(fx.snapshots.length);
  return { fx, s };
}

describe("streamed frames replayed through the reducer (U3 §11.4)", () => {
  test("partial-text-and-write: two text blocks, each shown once, the same after a reload", () => {
    const { s } = replay("partial-text-and-write");
    expect(s.live.texts).toEqual([]);
    expect(rendered(s)).toHaveLength(2);
  });

  test("the last delta after its assistant line: still one block per key, with the full text", () => {
    const late = replay("partial-text-and-write-late-delta").s;
    const full = replay("partial-text-and-write").s;
    expect(rendered(late)).toEqual(rendered(full));
  });

  test("partial-interrupt-mid-text: the interrupted block ends as exactly one block", () => {
    const { fx, s } = replay("partial-interrupt-mid-text");
    const interrupted = fx.frames.find((f) => f.type === "live" && f.texts?.length);
    const t = interrupted?.type === "live" ? interrupted.texts?.[0] : undefined;
    if (!t) throw new Error("no live text in the trace");
    const key = textRowKey(t.messageId, t.index);
    expect(rendered(s).filter((b) => b.key === key)).toHaveLength(1);
    expect(s.live.texts).toEqual([]);
    expect(s.retired.has(liveKey(t.messageId, t.index))).toBe(false); // the turn ended
  });

  test("partial-subagent: the main session's text blocks only, each once", () => {
    const { s } = replay("partial-subagent");
    expect(s.live.texts).toEqual([]);
    expect(rendered(s).length).toBeGreaterThan(0);
  });
});
